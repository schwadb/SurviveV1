#!/usr/bin/env bash
# =============================================================================
# SurviveV1 — Generate systemd service files from config
# Replaces hardcoded /mnt/survive paths with the configured SURVIVE_STORAGE_PATH
# Run after changing SURVIVE_STORAGE_PATH in config/survive.conf
# =============================================================================
set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
_CONF="$REPO_DIR/config/survive.conf"
[[ -f "$_CONF" ]] || _CONF="${_CONF}.example"   # fall back to shipped defaults
if [[ ! -f "$_CONF" ]]; then echo "[WARN] Config not found at $_CONF -- using defaults" >&2; else source "$_CONF"; fi

STORAGE_PATH="${SURVIVE_STORAGE_PATH:-/mnt/survive}"
SERVICE_TEMPLATE_DIR="$REPO_DIR/systemd"
SYSTEMD_DIR="/etc/systemd/system"

# The templates ship with User=pi, but Raspberry Pi Imager lets the user pick
# any login name. A unit naming a nonexistent user fails instantly with
# status=217/USER — before any of its own logging — so substitute the real
# account. SUDO_USER is the human who ran sudo; fall back to the repo owner.
SERVICE_USER="${SURVIVE_SERVICE_USER:-${SUDO_USER:-}}"
[[ -n "$SERVICE_USER" ]] || SERVICE_USER=$(stat -c '%U' "$REPO_DIR")
id "$SERVICE_USER" &>/dev/null || SERVICE_USER="pi"

# Binaries land in different prefixes depending on how they were installed
# (apt -> /usr/bin, upstream installers -> /usr/local/bin). systemd needs an
# absolute ExecStart and does no PATH lookup, so a template guessing wrong
# fails with 203/EXEC. Resolve each one here instead.
declare -A RESOLVED_BIN=()
for _b in kiwix-serve ollama kolibri martin; do
    _found=$(command -v "$_b" 2>/dev/null || true)
    # pip-installed tools (Kolibri, Calibre-Web) land in the venv, which is not
    # on root's PATH during install.
    [[ -n "$_found" ]] || [[ ! -x "/opt/survive/venv/bin/$_b" ]] \
        || _found="/opt/survive/venv/bin/$_b"
    RESOLVED_BIN[$_b]="${_found:-/usr/local/bin/$_b}"
done

GREEN='\033[0;32m'; BLUE='\033[0;34m'; NC='\033[0m'
info()    { echo -e "${BLUE}[SERVICES]${NC} $*"; }
success() { echo -e "${GREEN}[SERVICES]${NC} $*"; }

[[ $EUID -eq 0 ]] || { echo "Run with sudo: sudo bash $0"; exit 1; }

# Nightly update time (HH:MM, local). Anything malformed falls back to 02:30
# rather than producing a timer systemd refuses to load.
AUTO_UPDATE_TIME="${SURVIVE_AUTO_UPDATE_TIME:-02:30}"
[[ "$AUTO_UPDATE_TIME" =~ ^([01][0-9]|2[0-3]):[0-5][0-9]$ ]] || AUTO_UPDATE_TIME="02:30"

info "Generating service files for storage path: $STORAGE_PATH"
info "Services will run as user: $SERVICE_USER"
for _b in "${!RESOLVED_BIN[@]}"; do
    if [[ -x "${RESOLVED_BIN[$_b]}" ]]; then
        info "$_b -> ${RESOLVED_BIN[$_b]}"
    else
        info "$_b -> not installed (unit will stay DOWN until it is)"
    fi
done

for template in "$SERVICE_TEMPLATE_DIR"/*.service "$SERVICE_TEMPLATE_DIR"/*.timer; do
    [[ -f "$template" ]] || continue
    name=$(basename "$template")
    dest="$SYSTEMD_DIR/$name"

    # Replace /mnt/survive with the configured storage path, the template's
    # placeholder account with this machine's real user, the placeholder repo
    # path with this clone, and the nightly update time from survive.conf.
    sed -e "s|/mnt/survive|$STORAGE_PATH|g" \
        -e "s|/home/pi/SurviveV1|$REPO_DIR|g" \
        -e "s|^OnCalendar=.*|OnCalendar=*-*-* ${AUTO_UPDATE_TIME}:00|" \
        -e "s|^User=pi$|User=$SERVICE_USER|" \
        -e "s|/usr/local/bin/kiwix-serve|${RESOLVED_BIN[kiwix-serve]}|" \
        -e "s|/usr/local/bin/ollama|${RESOLVED_BIN[ollama]}|" \
        -e "s|/usr/local/bin/kolibri|${RESOLVED_BIN[kolibri]}|" \
        -e "s|/usr/local/bin/martin|${RESOLVED_BIN[martin]}|" \
        "$template" > "$dest"
    success "Installed $dest"
done

# The dashboard runs under systemd and does NOT source survive.conf, so
# selected keys are exported through an EnvironmentFile. Whitelisted only —
# survive.conf holds values (passwords, paths) that must not leak into the
# process environment wholesale.
ENV_FILE="/etc/default/survive"
{
    echo "# Generated by scripts/generate_services.sh -- do not edit by hand."
    echo "# Re-run: sudo bash scripts/generate_services.sh"
    for key in SURVIVE_OLLAMA_HOST SURVIVE_AI_MODEL SURVIVE_LIMITER_STORAGE \
               SURVIVE_STORAGE_PATH SURVIVE_AI_CHAT_TIMEOUT MAP_REGION \
               SURVIVE_AUTO_UPDATE SURVIVE_AUTO_UPDATE_TIME SURVIVE_AUTO_UPDATE_RATE_LIMIT; do
        val="${!key:-}"
        [[ -n "$val" ]] && echo "${key}=${val}"
    done
    # The dashboard runs from a copy under /opt/survive but launches scripts
    # from the clone (update, rescan, ZIM downloads).
    echo "SURVIVE_REPO_DIR=${REPO_DIR}"
} > "$ENV_FILE"
chmod 644 "$ENV_FILE"
success "Wrote $ENV_FILE"

systemctl daemon-reload
success "systemd daemon reloaded"

# Nightly content update: the timer is enabled only when survive.conf asks
# for it. The Status page can flip it later via the sudoers rule.
if [[ "${SURVIVE_AUTO_UPDATE:-false}" == "true" ]]; then
    systemctl enable --now survive-content-update.timer 2>/dev/null \
        && success "Nightly update timer enabled (${AUTO_UPDATE_TIME})" \
        || info "Could not enable survive-content-update.timer"
else
    systemctl disable --now survive-content-update.timer 2>/dev/null || true
    info "Nightly update timer off (SURVIVE_AUTO_UPDATE=true in survive.conf to enable)"
fi

echo ""
info "Services updated for storage path: $STORAGE_PATH"
info "Enable and start with:"
echo "  sudo systemctl enable survive-dashboard kiwix ollama martin-tiles calibre-web jellyfin survive-meshtastic"
echo "  sudo systemctl start survive-dashboard kiwix ollama martin-tiles"
